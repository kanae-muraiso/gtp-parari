// Runs only inside test-class-a-db's isolated PGlite database; never sends mail.
const assert = require('node:assert/strict');
module.exports = async function(db, {owner,learner,outsider,oldLearner}) {
  const q = (sql,args=[]) => db.query(sql,args);
  const school = (await q("insert into class_schools(owner_user_id,name,business_type) values($1,'受講者テスト','studio') returning id",[owner])).rows[0].id;
  const day = (await q("select ((now() at time zone 'Asia/Tokyo')::date+4)::text as day")).rows[0].day;
  const product=(await q("select gen_random_uuid() as id")).rows[0].id;
  await db.exec("set role service_role");
  await q("select save_school_content_product($1,$2,$3,'英語',$4,'{}')",[owner,school,product,JSON.stringify({audience:'minor',monthlyFee:5000,monthlyVisits:4,capacity:1,booking:'fixed',makeup:'notice',makeupExpiry:'next_month'})]);
  const slots=[];
  for (let i=0;i<2;i++) slots.push((await q("insert into school_classes(school_id,product_id,name,starts_on,starts_at,cadence) values($1,$2,$3,$4,$5,'weekly') returning id",[school,product,'枠'+i,day,i?'20:00':'18:00'])).rows[0].id);
  await q("update school_class_products set design=jsonb_set(design,'{classIds}',$2::jsonb) where id=$1",[product,JSON.stringify(slots)]);
  const members=[];
  for(let i=0;i<2;i++) members.push((await q("insert into school_enrollments(school_id,name,participation_mode,class_participation) values($1,$2,'assigned','fixed') returning id",[school,'子ども'+i])).rows[0].id);
  for(let i=0;i<2;i++) await q("insert into school_class_assignments(school_id,enrollment_id,class_id) values($1,$2,$3)",[school,members[i],slots[i]]);
  await db.exec('reset role');
  await q("update auth.users set email=$2,email_confirmed_at=now() where id=$1",[outsider,'parent@example.invalid']);
  await q("update auth.users set email=$2,email_confirmed_at=now() where id=$1",[learner,'child@example.invalid']);
  const cases=[];
  for(let i=0;i<2;i++) cases.push((await q("insert into school_admission_cases(id,school_id,name,source,briefing,test,decision,payment,applicant_email,learner_email,applicant_audience,application_fields,consent_at,enrollment_id,starts_on) values(gen_random_uuid(),$1,$2,'public','skip','skip','pending','free','parent@example.invalid',$3,'minor',$4,now(),$5,$6) returning id,registration_token,learner_token",[school,'子ども'+i,i?'other-child@example.invalid':'child@example.invalid',JSON.stringify({guardianEmail:'parent@example.invalid'}),members[i],day])).rows[0]);
  const confirm=(token,user)=>q('select confirm_class_registration($1,$2)',[token,user]);
  const access=(actor,member)=>q('select class_member_access($1,$2,$3) as allowed',[actor,school,member]);
  await db.exec('set role service_role');
  await assert.rejects(confirm(cases[0].registration_token,learner),{code:'22023'});
  await confirm(cases[0].registration_token,outsider); await confirm(cases[0].registration_token,outsider);
  await confirm(cases[1].registration_token,outsider);
  assert.equal((await access(outsider,members[0])).rows[0].allowed,true);
  assert.equal((await access(learner,members[0])).rows[0].allowed,false);
  await confirm(cases[0].learner_token,learner);
  assert.equal((await access(learner,members[0])).rows[0].allowed,true);
  assert.equal((await access(learner,members[1])).rows[0].allowed,false);
  const list=(await q('select class_participant_members($1,$2) as list',[outsider,school])).rows[0].list;
  assert.equal(list.length,2); assert.ok(list.every(item=>item.role==='guardian'&&item.startsOn===day));
  const read=(actor,member)=>q('select read_class_school_member($1,$2,$3) as school',[actor,school,member]);
  assert.equal((await read(learner,members[1])).rows[0].school,null);
  assert.deepEqual((await read(outsider,members[0])).rows[0].school.classes.map(x=>x.id),[slots[0]]);
  // Wrong-account use and re-binding are rejected, even if an email has been reused.
  await db.exec('reset role');
  await q("update auth.users set email='parent@example.invalid',email_confirmed_at=now() where id=$1",[oldLearner]);
  await db.exec('set role service_role');
  await assert.rejects(confirm(cases[0].registration_token,oldLearner),{code:'22023'});
  const absence=(actor,index,absent=true,date=day)=>q('select report_class_member_absence($1,$2,$3,$4,$5,$6)',[actor,school,members[index],slots[index],date,absent]);
  await assert.rejects(absence(learner,1),{code:'P0002'});
  await assert.rejects(absence(outsider,0,true,'2020-01-01'),{code:'22023'});
  await absence(outsider,0); await absence(outsider,0);
  assert.equal((await q('select count(*)::int n from school_class_makeups where enrollment_id=$1',[members[0]])).rows[0].n,1);
  assert.equal((await q('select class_fixed_seat_count_on($1,$2,$3) as n',[school,slots[0],day])).rows[0].n,0);
  await absence(outsider,1);
  const credit=(await q('select id from school_class_makeups where enrollment_id=$1',[members[1]])).rows[0].id;
  await q('select reserve_priced_member_class_visit($1,$2,$3,$4,$5,$6,0)',[outsider,members[1],school,slots[0],day,credit]);
  await assert.rejects(absence(outsider,0,false),{code:'P0001'});
  await assert.rejects(absence(outsider,1,false),{code:'22023'});
  await q('select manage_class_member_visit($1,$2,$3,$4,$5,true)',[outsider,members[1],school,slots[0],day]);
  await absence(outsider,0,false); await absence(outsider,1,false);
  assert.equal((await q('select count(*)::int n from school_class_makeups where enrollment_id=any($1)',[members])).rows[0].n,0);
  await q("update school_enrollments set status='ended' where id=$1",[members[0]]);
  assert.equal((await access(outsider,members[0])).rows[0].allowed,false);
  await db.exec('reset role');
  await q('update class_schools set archived_at=now() where id=$1',[school]);
  await db.exec('set role service_role');
  assert.deepEqual((await q('select class_participant_members($1,$2) as list',[outsider,school])).rows[0].list,[]);
  // Direct adult applications cannot enter the roster until their verified account is connected.
  await db.exec('reset role');
  const adultSchool=(await q("insert into class_schools(owner_user_id,name,business_type) values($1,'成人受付','studio') returning id",[owner])).rows[0].id;
  await q("insert into school_admission_settings(school_id,terms,labels,briefing,test,proxy) values($1,'','{}',false,false,false)",[adultSchool]);
  await q("insert into school_classes(school_id,name,starts_on,starts_at,cadence) values($1,'成人クラス',$2,'18:00','weekly')",[adultSchool,day]);
  const adult=(await q("insert into school_admission_cases(id,school_id,name,source,briefing,test,decision,payment,applicant_email,applicant_audience,consent_at,agreed_terms,starts_on) values(gen_random_uuid(),$1,'成人本人','public','skip','skip','approved','free','child@example.invalid','adult',now(),'',$2) returning id,registration_token",[adultSchool,day])).rows[0];
  await db.exec('set role service_role');
  await assert.rejects(q('select finish_class_admission($1,$2,$3)',[owner,adultSchool,adult.id]),{code:'P0006'});
  await confirm(adult.registration_token,learner);
  await q('select finish_class_admission($1,$2,$3)',[owner,adultSchool,adult.id]);
  assert.equal((await q('select user_id from school_enrollments where school_id=$1',[adultSchool])).rows[0].user_id,learner);
  for(const role of ['anon','authenticated']) {
    await db.exec('reset role; set role '+role);
    await assert.rejects(access(outsider,members[1]),{code:'42501'});
    await assert.rejects(confirm(cases[0].registration_token,outsider),{code:'42501'});
    await assert.rejects(q('select * from school_attendance'),{code:'42501'});
  }
  await db.exec('reset role');
  console.log('PASS: verified account links, two-child guardian access, identity isolation, absence/makeup capacity and role grants.');
};
