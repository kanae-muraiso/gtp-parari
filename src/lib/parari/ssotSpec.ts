/**
 * PART: PARARI SSOT SPEC v1
 * コメント:
 * - 新エディタ対応のための最小SSOT正式仕様
 * - importer / exporter の基準とする
 * - 人間可読な仕様書として保持（ロジックは持たない）
 */

/**
 * =============================
 * 0. 基本方針
 * =============================
 * - SSOT は保存形式
 * - Editor は操作形式
 * - importer/exporter が変換を担当
 * - 編集中は SSOT を直接操作しない
 */

/**
 * =============================
 * 1. 文書構造
 * =============================
 * 構成要素:
 * - BOOK
 * - PAGE
 * - 本文（無印テキスト）
 * - モジュールブロック
 * - インライン装飾
 */

/**
 * =============================
 * 2. BOOK
 * =============================
 */

/**
 * 形式A:
 * [BOOK]
 * title: タイトル
 *
 * 形式B:
 * [BOOK]タイトル
 */

/**
 * 主なメタキー:
 * title
 * subtitle
 * url
 * time
 * place
 * topics
 * displayMode
 * expiresAt
 * mode
 * cover
 * toc
 * coverImage
 * memo
 */

/**
 * exporter:
 * - 形式Aで出力可
 * importer:
 * - A/B 両方受理
 */

/**
 * =============================
 * 3. PAGE
 * =============================
 */

/**
 * [PAGE]章タイトル
 * 本文
 *
 * または
 * [PAGE]
 * 本文
 */

/**
 * - PAGEはページ開始を示す
 * - 章タイトルは構造情報（装飾ではない）
 */

/**
 * =============================
 * 4. 本文（TextBlock）
 * =============================
 */

/**
 * - [T] は使用しない
 * - タグで始まらない連続行は本文とみなす
 * - 内部では TextBlock として扱う
 * - モジュール出現で一旦終了
 */

/**
 * 例:
 *
 * ここから本文
 *
 * [IMAGE url="..."]
 *
 * ここから次の本文
 */

/**
 * =============================
 * 5. インライン
 * =============================
 */

/**
 * 太字:
 * **text**
 */

/**
 * カラー:
 * !!text!!
 * !!text!!(red)
 */

/**
 * リンク:
 * [[label]](url)
 */

/**
 * =============================
 * 6. モジュール
 * =============================
 */

/**
 * 基本形:
 * [MODULE key="value"]
 *
 * 複数属性:
 * [MODULE key1="v1" key2="v2"]
 */

/**
 * 例:
 * [IMAGE url="https://..."]
 * [YOUTUBE url="https://..."]
 * [APPLICATION id="abc123"]
 * [MAP place="京都" url="https://..."]
 */

/**
 * 特徴:
 * - 1行完結
 * - 閉じタグなし
 * - []内で完結
 */

/**
 * =============================
 * 7. IMAGE旧記法互換
 * =============================
 */

/**
 * 旧:
 * [IMAGE]
 * https://...
 *
 * 新:
 * [IMAGE url="https://..."]
 */

/**
 * importer:
 * - 旧/新 両方受理
 * exporter:
 * - 新記法のみ出力
 */

/**
 * =============================
 * 8. importer/exporter責務
 * =============================
 */

/**
 * importer:
 * - 旧形式吸収
 * - 本文をTextBlock化
 * - モジュールをBlock化
 */

/**
 * exporter:
 * - 新仕様で統一出力
 * - IMAGEは1行記法
 * - 本文は無印
 */

/**
 * =============================
 * 9. editor構造
 * =============================
 */

/**
 * 構造:
 * - BOOK
 * - PAGE
 * - 見出し
 * - 本文
 * - モジュール
 *
 * 装飾:
 * - 太字
 * - カラー
 * - リンク
 */

/**
 * =============================
 * 10. 保留事項
 * =============================
 */

/**
 * - モジュール一覧の完全確定
 * - 属性仕様の拡張
 * - viewerレンダリング詳細
 * - BOOK/PAGEの将来属性化
 */

